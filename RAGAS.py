"""
Standalone RAGAS evaluation script for the DIEM RAG chatbot.

This script does not call the chatbot pipeline again. Instead, it reuses
previously saved test logs (question, generated answer, retrieved parent
chunk ids) together with a manually corrected ground truth file, resolves
the retrieved chunk ids against the parent chunk store, assembles a RAGAS
evaluation dataset, and runs the evaluation with the following metrics:

- Faithfulness (reference-free)
- Response Relevancy (reference-free)
- LLM Context Precision With Reference (reference-based, uses ground truth)
- LLM Context Recall (reference-based, uses ground truth)
- Answer Correctness (reference-based, uses ground truth)

Expected input files:
- TEST_LOG_PATH: log containing the questions, the answers generated by the
  chatbot, and the debug retrieval sections with the "Kept N documents out
  of top N" block listing the retrieved parent chunk ids.
- GROUND_TRUTH_LOG_PATH: log with the same "## Turn N" structure, where the
  answer section has been manually corrected. Only the corrected answer is
  used as ground truth; its debug/retrieval section is ignored.
- config.PARENT_STORE_PATH: JSON file mapping parent chunk id to an object
  containing at least a "page_content" field.

Turns are matched by their "## Turn N" number between the two log files.

Usage:
    python RAGAS.py --test-log test_results/62_test.md --ground-truth test_results/62_adjusted.md
"""

import argparse
import json
import logging
import re
from pathlib import Path

import pandas as pd
from ragas import RunConfig, evaluate
from ragas.dataset_schema import EvaluationDataset
from ragas.metrics import (
    AnswerCorrectness,
    Faithfulness,
    LLMContextPrecisionWithReference,
    LLMContextRecall,
    ResponseRelevancy,
)

import config
from config import PARENT_STORE_PATH

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

# When True, enables a lightweight progress view (one INFO line per HTTP
# request sent to the judge LLM, e.g. "HTTP Request: POST .../chat/completions
# 200 OK"). This only affects logging verbosity: individual job failures are
# always handled non-blockingly (logged and recorded as NaN), regardless of
# this flag, so a long/unattended run never stops on a single error.
DEBUG_MODE = True

# Default inputs (overridable from the command line).
TEST_LOG_PATH = Path("./test_results/62_test.md")
GROUND_TRUTH_LOG_PATH = Path("./test_results/62_adjusted.md")

ASSEMBLED_DATASET_PATH = Path("./test_results/ragas_dataset.json")
RESULTS_CSV_PATH = Path("./test_results/ragas_results.csv")

# The default max_tokens used by the chatbot's judge (2048) is too low for
# some RAGAS metrics, which can produce long structured outputs (e.g. the
# list of atomic statements generated by Faithfulness) when evaluating long
# retrieved contexts. A dedicated judge instance is built with this limit.
JUDGE_MAX_TOKENS = 4096

# RAGAS RunConfig tuning. The default max_workers (16) issues too many
# concurrent requests for the configured OpenRouter model, causing
# TimeoutError on several jobs. Fully sequential execution (max_workers=1)
# with a generous per-request timeout avoids any concurrency-related
# rate-limiting/queueing on the OpenRouter side, at the cost of a longer
# total run time.
JUDGE_MAX_WORKERS = 1
JUDGE_TIMEOUT_SECONDS = 600

TURN_PATTERN = re.compile(r"##\s*Turn\s+(\d+)")
QUESTION_PATTERN = re.compile(r"\*\*Question:\*\*\s*(.+)")
ANSWER_PATTERN = re.compile(r"###\s*Answer\s*(.*?)(?:\n###\s|\Z)", re.DOTALL)
CHUNK_ID_PATTERN = re.compile(r"ID:\s*([0-9a-fA-F]{16,})")


# ---------------------------------------------------------------------------
# Parsing helpers
# ---------------------------------------------------------------------------

def parse_turn_log(filepath: Path) -> dict:
    """
    Parse a test log file structured in '## Turn N' blocks and extract, for
    each turn, the question text, the answer text, and the list of parent
    chunk ids that were kept after reranking and injected into the prompt.

    Parameters
    ----------
    filepath : Path
        Path to the log file to parse.

    Returns
    -------
    dict
        Mapping from turn number (int) to a dictionary with keys
        'question', 'answer', and 'chunk_ids'.
    """
    content = filepath.read_text(encoding="utf-8")

    turn_starts = list(TURN_PATTERN.finditer(content))
    if not turn_starts:
        raise ValueError(f"No '## Turn N' blocks found in {filepath}")

    parsed_turns = {}
    for i, match in enumerate(turn_starts):
        turn_number = int(match.group(1))
        block_start = match.end()
        block_end = turn_starts[i + 1].start() if i + 1 < len(turn_starts) else len(content)
        block = content[block_start:block_end]

        question_match = QUESTION_PATTERN.search(block)
        answer_match = ANSWER_PATTERN.search(block)
        chunk_ids = CHUNK_ID_PATTERN.findall(block)

        if not question_match:
            print(f"[WARNING] Turn {turn_number}: question not found, skipping turn.")
            continue
        if not answer_match:
            print(f"[WARNING] Turn {turn_number}: answer not found, skipping turn.")
            continue
        if not chunk_ids:
            print(f"[WARNING] Turn {turn_number}: no retrieved chunk ids found.")

        parsed_turns[turn_number] = {
            "question": question_match.group(1).strip(),
            "answer": answer_match.group(1).strip(),
            "chunk_ids": chunk_ids,
        }

    return parsed_turns


def load_parent_store(filepath: Path) -> dict:
    """
    Load the parent chunk store JSON file and build a mapping from chunk id
    to its page content.

    Parameters
    ----------
    filepath : Path
        Path to the parent chunk store JSON file.

    Returns
    -------
    dict
        Mapping from chunk id (str) to page content (str).
    """
    with open(filepath, "r", encoding="utf-8") as f:
        raw_store = json.load(f)

    return {
        chunk_id: entry.get("page_content", "")
        for chunk_id, entry in raw_store.items()
    }


def build_ragas_records(test_turns: dict, ground_truth_turns: dict, parent_store: dict) -> list:
    """
    Combine parsed test turns, ground truth turns, and the parent chunk
    store into a list of records ready to be consumed by RAGAS.

    Parameters
    ----------
    test_turns : dict
        Output of parse_turn_log for the test log (system answers and
        retrieved chunk ids).
    ground_truth_turns : dict
        Output of parse_turn_log for the ground truth log (manually
        corrected answers).
    parent_store : dict
        Mapping from chunk id to page content.

    Returns
    -------
    list
        List of dictionaries with keys 'user_input', 'response',
        'retrieved_contexts', and 'reference'.
    """
    records = []
    common_turns = sorted(set(test_turns) & set(ground_truth_turns))
    missing_in_gt = sorted(set(test_turns) - set(ground_truth_turns))

    if missing_in_gt:
        print(f"[WARNING] Turns present in the test log but missing in the "
              f"ground truth log, skipped: {missing_in_gt}")

    for turn_number in common_turns:
        test_entry = test_turns[turn_number]
        gt_entry = ground_truth_turns[turn_number]

        contexts = []
        for chunk_id in test_entry["chunk_ids"]:
            page_content = parent_store.get(chunk_id)
            if page_content is None:
                print(f"[WARNING] Turn {turn_number}: chunk id {chunk_id} "
                      f"not found in parent store, skipped.")
                continue
            contexts.append(page_content)

        if not contexts:
            print(f"[WARNING] Turn {turn_number}: no resolved contexts, "
                  f"turn excluded from the dataset.")
            continue

        records.append({
            "turn": turn_number,
            "user_input": test_entry["question"],
            "response": test_entry["answer"],
            "retrieved_contexts": contexts,
            "reference": gt_entry["answer"],
        })

    return records


# ---------------------------------------------------------------------------
# Evaluation
# ---------------------------------------------------------------------------

def estimate_llm_calls(records: list) -> dict:
    """
    Compute the expected number of judge LLM calls that the evaluation will
    issue, based on the fixed call count of each metric and, for Context
    Precision, the number of retrieved contexts per turn.

    Call counts per turn, determined by inspecting each metric's
    implementation:
    - Faithfulness: 2 (statement generation + NLI verdict)
    - Response Relevancy: 1 (generated with a single request for multiple
      completions, regardless of the configured strictness)
    - Context Precision (with reference): 1 per retrieved context
    - Context Recall: 1 (statement-level attribution of the reference
      against the retrieved contexts, in a single request)
    - Answer Correctness: 3 (2 statement generations + 1 classification)

    Parameters
    ----------
    records : list
        List of records as produced by build_ragas_records, each containing
        a 'retrieved_contexts' key.

    Returns
    -------
    dict
        Per-metric and total expected number of LLM calls.
    """
    faithfulness_calls = 2 * len(records)
    response_relevancy_calls = 1 * len(records)
    context_recall_calls = 1 * len(records)
    answer_correctness_calls = 3 * len(records)
    context_precision_calls = sum(len(r["retrieved_contexts"]) for r in records)

    total_calls = (
        faithfulness_calls
        + response_relevancy_calls
        + context_precision_calls
        + context_recall_calls
        + answer_correctness_calls
    )

    return {
        "faithfulness": faithfulness_calls,
        "response_relevancy": response_relevancy_calls,
        "context_precision": context_precision_calls,
        "context_recall": context_recall_calls,
        "answer_correctness": answer_correctness_calls,
        "total": total_calls,
    }


def configure_debug_logging() -> None:
    """
    Enable a lightweight progress view for the evaluation run: one INFO line
    per HTTP request made to the judge LLM endpoint (via the httpx logger
    used internally by the OpenAI-compatible client), while suppressing all
    other verbose output (LangChain full prompt/completion dumps, RAGAS
    internal DEBUG logs).
    """
    logging.basicConfig(
        level=logging.WARNING,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
    )
    logging.getLogger("httpx").setLevel(logging.INFO)


def build_embeddings_model():
    """Embedding model used by RAGAS (the same one configured for indexing)."""
    return config.get_embeddings()


def run_evaluation(records: list) -> pd.DataFrame:
    """
    Run the RAGAS evaluation on the assembled records.

    Parameters
    ----------
    records : list
        List of records as produced by build_ragas_records, each containing
        the 'turn' key in addition to the RAGAS schema fields.

    Returns
    -------
    pandas.DataFrame
        Per-question metric scores, including the original turn number.
    """
    turn_numbers = [record["turn"] for record in records]
    ragas_records = [
        {k: v for k, v in record.items() if k != "turn"}
        for record in records
    ]

    dataset = EvaluationDataset.from_list(ragas_records)
    embeddings_model = build_embeddings_model()

    # Dedicated judge instance with a larger output budget (see JUDGE_MAX_TOKENS).
    judge_llm = config.build_chat_model(temperature=0.0, max_tokens=JUDGE_MAX_TOKENS)

    metrics = [
        Faithfulness(),
        ResponseRelevancy(),
        LLMContextPrecisionWithReference(),
        LLMContextRecall(),
        AnswerCorrectness(),
    ]

    run_config = RunConfig(
        timeout=JUDGE_TIMEOUT_SECONDS,
        max_workers=JUDGE_MAX_WORKERS,
    )

    result = evaluate(
        dataset=dataset,
        metrics=metrics,
        llm=judge_llm,
        embeddings=embeddings_model,
        run_config=run_config,
        # Individual job failures (timeouts, parsing errors, etc.) are
        # always logged and recorded as NaN for that specific score, never
        # raised. This keeps a long/unattended run going to completion
        # regardless of DEBUG_MODE, which only controls logging verbosity.
        raise_exceptions=False,
    )

    result_df = result.to_pandas()
    result_df.insert(0, "turn", turn_numbers)
    return result_df


def save_results(result_df: pd.DataFrame, output_path: Path) -> None:
    """
    Save per-question results together with an appended row containing the
    average score for each metric.

    Parameters
    ----------
    result_df : pandas.DataFrame
        Per-question metric scores.
    output_path : Path
        Destination CSV path.
    """
    numeric_columns = result_df.select_dtypes(include="number").columns
    numeric_columns = [c for c in numeric_columns if c != "turn"]

    average_row = {col: result_df[col].mean() for col in numeric_columns}
    average_row["turn"] = "AVERAGE"

    final_df = pd.concat([result_df, pd.DataFrame([average_row])], ignore_index=True)
    final_df.to_csv(output_path, index=False)
    print(f"Results saved to {output_path}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    """
    Execute the full evaluation pipeline: parse both log files, resolve the
    retrieved contexts, assemble the RAGAS dataset, run the evaluation, and
    persist both the assembled dataset and the final results.
    """
    parser = argparse.ArgumentParser(description="RAGAS evaluation of saved chatbot test logs.")
    parser.add_argument("--test-log", type=Path, default=TEST_LOG_PATH,
                        help="batch_test.py log with the generated answers and retrieved chunk ids")
    parser.add_argument("--ground-truth", type=Path, default=GROUND_TRUTH_LOG_PATH,
                        help="same log with manually corrected answers (used as reference)")
    args = parser.parse_args()

    if DEBUG_MODE:
        configure_debug_logging()
        print("Debug mode enabled: HTTP request progress logging is active.")

    print(f"Parsing test log: {args.test_log}")
    test_turns = parse_turn_log(args.test_log)

    print(f"Parsing ground truth log: {args.ground_truth}")
    ground_truth_turns = parse_turn_log(args.ground_truth)

    print(f"Loading parent chunk store: {PARENT_STORE_PATH}")
    parent_store = load_parent_store(Path(PARENT_STORE_PATH))

    print("Building RAGAS records.")
    records = build_ragas_records(test_turns, ground_truth_turns, parent_store)
    print(f"Assembled {len(records)} records out of {len(test_turns)} test turns.")

    ASSEMBLED_DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(ASSEMBLED_DATASET_PATH, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)
    print(f"Assembled dataset saved to {ASSEMBLED_DATASET_PATH}")

    call_estimate = estimate_llm_calls(records)
    print(
        "Estimated judge LLM calls: "
        f"faithfulness={call_estimate['faithfulness']}, "
        f"response_relevancy={call_estimate['response_relevancy']}, "
        f"context_precision={call_estimate['context_precision']}, "
        f"context_recall={call_estimate['context_recall']}, "
        f"answer_correctness={call_estimate['answer_correctness']}, "
        f"total={call_estimate['total']}"
    )

    print("Running RAGAS evaluation.")
    result_df = run_evaluation(records)

    save_results(result_df, RESULTS_CSV_PATH)


if __name__ == "__main__":
    main()